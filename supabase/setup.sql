create or replace function public.guard_prediction_write()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  kickoff timestamptz;
begin
  if tg_op = 'UPDATE' then
    if new.user_id <> old.user_id or new.match_id <> old.match_id then
      raise exception 'Não é permitido trocar o usuário ou o jogo de um palpite.';
    end if;
    new.created_at := old.created_at;
  end if;

  if auth.uid() is not null and new.user_id <> auth.uid() then
    raise exception 'Você só pode salvar seu próprio palpite.';
  end if;

  select kickoff_at into kickoff from public.matches where id = new.match_id;
  if kickoff is null then
    raise exception 'Partida não encontrada.';
  end if;

  if now() >= kickoff then
    raise exception 'Os palpites desta partida já foram encerrados.';
  end if;

  new.updated_at := now();
  if tg_op = 'INSERT' then new.created_at := now(); end if;
  return new;
end;
$$;

drop trigger if exists guard_prediction_before_write on public.predictions;
create trigger guard_prediction_before_write
  before insert or update on public.predictions
  for each row execute function public.guard_prediction_write();

create or replace function public.guard_match_result()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  new.updated_at := now();

  if tg_op = 'UPDATE' and
     (new.home_score is distinct from old.home_score or new.away_score is distinct from old.away_score) then
    if (new.home_score is null) <> (new.away_score is null) then
      raise exception 'Informe os dois placares ou deixe os dois vazios.';
    end if;

    if new.home_score is not null and now() < new.kickoff_at then
      raise exception 'O resultado só pode ser informado depois do início da partida.';
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists guard_match_before_write on public.matches;
create trigger guard_match_before_write
  before insert or update on public.matches
  for each row execute function public.guard_match_result();

