create or replace function public.match_has_started(p_match_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (select now() >= kickoff_at from public.matches where id = p_match_id),
    false
  );
$$;

create or replace function public.match_is_open(p_match_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (select now() < kickoff_at from public.matches where id = p_match_id),
    false
  );
$$;

