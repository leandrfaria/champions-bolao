create or replace function public.get_prediction_presence(p_match_ids uuid[])
returns table (
  match_id uuid,
  user_id uuid,
  display_name text,
  has_predicted boolean
)
language sql
stable
security definer
set search_path = public
as $$
  select
    m.id as match_id,
    p.id as user_id,
    p.display_name,
    exists (
      select 1 from public.predictions pr
      where pr.match_id = m.id and pr.user_id = p.id
    ) as has_predicted
  from public.matches m
  cross join public.profiles p
  where auth.uid() is not null
    and m.id = any(p_match_ids)
  order by m.kickoff_at, p.display_name;
$$;

create or replace function public.set_active_season(p_season_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  season_label text;
begin
  if not public.is_admin() then
    raise exception 'Apenas administradores podem alterar a temporada ativa.';
  end if;

  if not exists (select 1 from public.seasons where id = p_season_id) then
    raise exception 'Temporada não encontrada.';
  end if;

  update public.seasons set is_active = false where is_active = true and id <> p_season_id;
  update public.seasons set is_active = true where id = p_season_id;

  select name into season_label from public.seasons where id = p_season_id;
  insert into public.audit_logs (actor_user_id, action, entity_type, entity_id, metadata)
  values (auth.uid(), 'season_activated', 'season', p_season_id, jsonb_build_object('season_name', season_label));
end;
$$;

