create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  local_name text;
  pretty_name text;
  user_role text;
begin
  local_name := lower(split_part(new.email, '@', 1));

  pretty_name := case local_name
    when 'leandro' then 'Leandro'
    when 'caio' then 'Caio'
    when 'joao' then 'João'
    when 'matheus' then 'Matheus'
    when 'leonardo' then 'Leonardo'
    when 'bruno' then 'Bruno'
    else coalesce(new.raw_user_meta_data->>'display_name', initcap(local_name), 'Jogador')
  end;

  user_role := case
    when lower(new.email) = 'leandro@champions-bolao.app' then 'admin'
    else 'user'
  end;

  insert into public.profiles (id, display_name, role)
  values (new.id, pretty_name, user_role)
  on conflict (id) do update
    set display_name = excluded.display_name;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

